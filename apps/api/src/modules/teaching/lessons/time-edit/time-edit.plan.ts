import { MINUTE_MS } from '@ab/shared';
import type { ConflictKind, LessonStatus, PayoutStatus, TimeEditMode } from '@ab/shared';
import { badRequest } from '@/common/http/errors';
import { localDateOf } from '@/modules/teaching/scheduling/occurrences/horizon';
// Pure decisions of «عدّل الوقت» (R-SCH-11, docs/10 §10): what a time edit may do to a lesson,
// which side effects it sets in motion, and whether a payout month stands in its way.

export type TimeEditInput = {
  mode: TimeEditMode;
  now: Date;
  /** The lesson as stored. */
  current: { startsAt: Date; endsAt: Date };
  /** What the admin asked for. */
  request: { startsAt: Date; durationMin: number; reason?: string; notify?: boolean };
  /** The teacher's and every student's tz: a correction must stay on the same day for all. */
  zones: readonly string[];
};

export type TimeEditPlan = {
  mode: TimeEditMode;
  start: Date;
  end: Date;
  startChanged: boolean;
  durationChanged: boolean;
  reason: string | null;
  /** Open lesson, new start: old-time messages expire, reminder keys are freed. */
  retimeOpen: boolean;
  /** Held lesson, new start or length: the report PDF is re-rendered. */
  refreshPdf: boolean;
  /** Queue the guardian's confirmation (a future lesson whose start changed, notify not off). */
  notify: boolean;
  /** A correction records what happened, so the weekly grid and time-off do not apply to it. */
  ignoredConflicts: readonly ConflictKind[];
};

const durationOf = (start: Date, end: Date): number => Math.round((end.getTime() - start.getTime()) / MINUTE_MS);

/** The request already holds: a replay (or a no-op) writes nothing. */
export const isSameTime = (current: TimeEditInput['current'], request: TimeEditInput['request']): boolean =>
  request.startsAt.getTime() === current.startsAt.getTime() &&
  request.durationMin === durationOf(current.startsAt, current.endsAt);

/** The 400s of a move (date_in_past) and of a correction (future, cross-day, reason), in that order. */
function validate({ mode, now, current, request, zones }: TimeEditInput, planned: { end: Date; reason: string | null }): void {
  const start = request.startsAt;
  if (mode === 'move') {
    if (start.getTime() <= now.getTime()) throw badRequest('date_in_past');
    return;
  }
  if (planned.end.getTime() > now.getTime()) throw badRequest('date_in_future');
  if (zones.some((tz) => localDateOf(start, tz) !== localDateOf(current.startsAt, tz))) throw badRequest('correction_cross_day');
  if (!planned.reason) throw badRequest('reason_required');
}

/**
 * Validates and plans one edit. 400 `date_in_past` (move to the past), `date_in_future`,
 * `correction_cross_day`, `reason_required` (correct). A correction keeps the local day so lesson
 * numbers, the FIFO package balance and the payout month do not move; status, attendance and
 * `chargeable` stay frozen (an `excused` lesson is not re-judged against the late-cancel window).
 */
export function planTimeEdit(input: TimeEditInput): TimeEditPlan {
  const { mode, current, request } = input;
  const start = request.startsAt;
  const end = new Date(start.getTime() + request.durationMin * MINUTE_MS);
  const reason = request.reason?.trim() || null;
  validate(input, { end, reason });
  const startChanged = start.getTime() !== current.startsAt.getTime();
  const durationChanged = request.durationMin !== durationOf(current.startsAt, current.endsAt);
  return {
    mode,
    start,
    end,
    startChanged,
    durationChanged,
    reason,
    retimeOpen: mode === 'move' && startChanged,
    refreshPdf: mode === 'correct' && (startChanged || durationChanged),
    notify: mode === 'move' && startChanged && request.notify !== false,
    ignoredConflicts: mode === 'correct' ? ['outside_availability', 'time_off'] : [],
  };
}

type PayoutScope = { month: string };
type PayoutScopeInput = {
  plan: TimeEditPlan;
  status: LessonStatus;
  teacherTz: string;
  paidStatuses: readonly LessonStatus[];
};

/**
 * The payout month a time edit can collide with (`YYYY-MM` in the teacher's tz), or null.
 * - move: the NEW month, where an open lesson could later be paid.
 * - correct: only a paid-status lesson whose length changed changes the payout line (the
 *   breakdown stores lesson ids, so a start-only shift on the same day changes nothing).
 */
export function payoutScope({ plan, status, teacherTz, paidStatuses }: PayoutScopeInput): PayoutScope | null {
  if (plan.mode === 'correct' && !(plan.durationChanged && paidStatuses.includes(status))) return null;
  return { month: localDateOf(plan.start, teacherTz).slice(0, 7) };
}

/** Approved and paid months are frozen (E3); a draft is regenerated by «احسب مستحقات الشهر». */
export const isPayoutLocked = (status: PayoutStatus | null): boolean => status === 'approved' || status === 'paid';
