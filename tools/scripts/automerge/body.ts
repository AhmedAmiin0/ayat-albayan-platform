import type { Pr } from './facts.schemas.ts';

/** Squash commits on develop carry no tool or assistant attribution. */
const ATTRIBUTION = /generated with|generated by|claude\.ai\/code|co-authored-by/i;
const DANGLING = /(\n\s*-{3,}\s*)+$/;

export const subjectOf = (pr: Pick<Pr, 'number' | 'title'>): string =>
  `${pr.title} (#${String(pr.number)})`;

export function scrubBody(body: string): string {
  const kept = body.split(/\r?\n/).filter((line) => !ATTRIBUTION.test(line));
  return kept.join('\n').trimEnd().replace(DANGLING, '').trimEnd();
}
