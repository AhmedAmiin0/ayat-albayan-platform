import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { stripFooter } from './strip-footer.mjs';

const SCRIPT = fileURLToPath(new URL('./strip-footer.mjs', import.meta.url));
const FOOTER = '_Generated by [Some Tool](https://example.com/code)_';
const EMOJI_FOOTER = '🤖 Generated with [Some Tool](https://example.com)';

test('removes the footer and the separator above it', () => {
  assert.equal(stripFooter(`## Scope\n\nText.\n\n\n---\n${FOOTER}`), '## Scope\n\nText.\n');
});

test('removes the emoji form that says «with»', () => {
  assert.equal(stripFooter(`Text.\n\n${EMOJI_FOOTER}\n`), 'Text.\n');
});

test('reads bodies with CRLF line ends', () => {
  assert.equal(stripFooter(`Text.\r\n---\r\n${FOOTER}\r\n`), 'Text.\n');
});

test('leaves a body without the footer alone', () => {
  assert.equal(stripFooter('Text.\n\n---\nMore text.\n'), null);
  assert.equal(stripFooter('Generated by the release step, see #12.'), null);
  assert.equal(stripFooter(''), null);
});

test('the command prints the clean body and exits 0 only when it removed a footer', () => {
  const run = (input) => spawnSync(process.execPath, [SCRIPT], { input, encoding: 'utf8' });
  const removed = run(`Text.\n${FOOTER}\n`);
  assert.deepEqual([removed.status, removed.stdout], [0, 'Text.\n']);
  const kept = run('Text.\n');
  assert.deepEqual([kept.status, kept.stdout], [1, '']);
});
