// Slots → calendar-diff.sql: the calendar's standing slots in a temp table, compared with the
// platform's active weekly rules (schedule_rules × schedule_rule_students × byday), both as Riyadh
// wall time. Report only: one transaction that ends in ROLLBACK, nothing is written.

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

export function valuesOf(slots) {
  return slots
    .map((s) => `  (${q(s.teacher)}, ${q(s.student)}, ${s.weekday}, ${q(s.at)}, ${q(s.tz)}, ${s.minutes ?? 'null'}, ${s.series})`)
    .join(',\n');
}

const HEADER = `-- calendar-diff.sql — Google Calendar (the old Apps Script calendars) vs the platform's weekly rules.
-- Generated by tools/scripts/calendar-diff.mjs. Holds students' names: run it, never commit it.
-- Report only (ends in ROLLBACK). Weekdays as schedule_rules.byday: 0 = الأحد … 6 = السبت.
-- status per calendar slot: ok · time_differs · day_differs · other_teacher · missing_rule · no_student · no_teacher`;

const SETUP = `begin;

create function pg_temp.norm(t text) returns text language sql immutable as $$
  select btrim(regexp_replace(lower(translate(
    regexp_replace(coalesce(t, ''), '[ً-ٟـ]', '', 'g'),
    'أإآٱىةؤئ', 'اااايهوي')), '\\s+', ' ', 'g'))
$$;
create function pg_temp.riyadh(at time, tz text) returns time language sql stable as $$
  select (((current_date + at) at time zone tz) at time zone 'Asia/Riyadh')::time
$$;

create temp table cal (teacher_like text, student text, weekday int, at time, tz text, minutes int, series int) on commit drop;`;

const COMPARE = `
create temp table plat on commit drop as
select r.id as rule_id, t.id as teacher_id, coalesce(t.display_name_ar, '') as t_ar, coalesce(t.display_name_en, '') as t_en,
       s.id as student_id, s.name as student, d.weekday::int as weekday, pg_temp.riyadh(r.start_time_local, r.tz) as at_riyadh,
       r.duration_min::text as minutes
from public.schedule_rules r
join public.teachers t on t.id = r.teacher_id
join public.schedule_rule_students rs on rs.rule_id = r.id
join public.students s on s.id = rs.student_id
cross join unnest(r.byday) as d(weekday)
where r.status = 'active' and (r.ends_on is null or r.ends_on >= current_date);

create temp table cal_t on commit drop as
select c.*, pg_temp.riyadh(c.at, c.tz) as at_riyadh,
       (select array_agg(t.id) from public.teachers t
         where pg_temp.norm(t.display_name_en) like '%' || pg_temp.norm(c.teacher_like) || '%'
            or pg_temp.norm(t.display_name_ar) like '%' || pg_temp.norm(c.teacher_like) || '%') as teacher_ids
from cal c;

\\echo '== 1. every calendar slot, with what the platform has for it =='
select c.teacher_like as teacher, c.student, c.weekday, to_char(c.at_riyadh, 'HH24:MI') as cal_riyadh, c.series,
  case
    when coalesce(cardinality(c.teacher_ids), 0) <> 1 then 'no_teacher'
    when exists (select 1 from plat p where p.teacher_id = c.teacher_ids[1] and pg_temp.norm(p.student) = pg_temp.norm(c.student)
                   and p.weekday = c.weekday and p.at_riyadh = c.at_riyadh) then 'ok'
    when exists (select 1 from plat p where p.teacher_id = c.teacher_ids[1] and pg_temp.norm(p.student) = pg_temp.norm(c.student)
                   and p.weekday = c.weekday) then 'time_differs'
    when exists (select 1 from plat p where p.teacher_id = c.teacher_ids[1] and pg_temp.norm(p.student) = pg_temp.norm(c.student)) then 'day_differs'
    when exists (select 1 from plat p where pg_temp.norm(p.student) = pg_temp.norm(c.student)) then 'other_teacher'
    when exists (select 1 from public.students s where pg_temp.norm(s.name) = pg_temp.norm(c.student)) then 'missing_rule'
    else 'no_student'
  end as status,
  (select string_agg(distinct p.weekday || ' ' || to_char(p.at_riyadh, 'HH24:MI') || ' ' || p.t_ar, ' · ')
     from plat p where pg_temp.norm(p.student) = pg_temp.norm(c.student)) as platform_has
from cal_t c order by status desc, teacher, student, weekday;

\\echo '== 2. platform slots of these teachers that the calendar does not have =='
select p.t_ar as teacher, p.student, p.weekday, to_char(p.at_riyadh, 'HH24:MI') as platform_riyadh, p.rule_id
from plat p
where p.teacher_id in (select unnest(teacher_ids) from cal_t)
  and not exists (select 1 from cal_t c where p.teacher_id = any(c.teacher_ids) and pg_temp.norm(c.student) = pg_temp.norm(p.student)
                    and c.weekday = p.weekday and c.at_riyadh = p.at_riyadh)
order by teacher, student, weekday;

\\echo '== 3. counts =='
select count(*) as calendar_slots, count(distinct student) as calendar_students from cal;

rollback;
`;

/** The whole script; `meta` = { calendars, today, skipped } for the header. */
export function buildSql(slots, meta) {
  const note = `-- ${meta.calendars} calendars, ${slots.length} slots still running on ${meta.today}; left out: ${JSON.stringify(meta.skipped)}`;
  const insert = slots.length ? `insert into cal values\n${valuesOf(slots)};\n` : '-- (no slots)\n';
  return `${HEADER}\n${note}\n${SETUP}\n${insert}${COMPARE}`;
}
