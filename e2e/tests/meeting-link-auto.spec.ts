import { randomUUID } from 'node:crypto';
import type { Page } from '@playwright/test';
import { ar, expect, test } from '../support/fixtures';
import { API, bearer, setSetting } from '../support/messages';
import { addDays, nextWeekSaturday, queuedFor, resetAbrar, riyadh, seedFamily, seedLesson, setAvailability, withSql } from '../support/schedule';

// settings.meeting_link_auto (owner 2026-10-12): ON = the messages carry the platform classroom,
// chosen when they are queued; lessons.meeting_link keeps the teacher's fixed link either way. The
// reminders job's family link (lesson_join_link per student) is covered by its unit tests
// (reminders.job.room.test.ts, reminders.room.test.ts): the 5-minute job has no trigger here.

const MEET = 'https://meet.google.com/e2e-auto-link';

/** The e2e teacher's fixed link set to MEET; returns the one to put back. */
async function setMeetLink(teacherId: string): Promise<string | null> {
  const [prev] = await withSql((sql) => sql<{ link: string | null }[]>`select meeting_link as link from public.teachers where id = ${teacherId}`);
  await withSql((sql) => sql`update public.teachers set meeting_link = ${MEET} where id = ${teacherId}`);
  return prev?.link ?? null;
}

async function restore(teacherId: string, link: string | null): Promise<void> {
  await setSetting('meeting_link_auto', false);
  await withSql((sql) => sql`update public.teachers set meeting_link = ${link} where id = ${teacherId}`);
}

/** A trial for a fresh family at `time` next Sunday (Riyadh), through POST /booking. */
async function bookTrial(page: Page, input: { teacherId: string; time: string; name: string }) {
  const sunday = addDays(nextWeekSaturday(), 1);
  const family = await seedFamily(`أم ${input.name}`, [input.name]);
  const res = await page.request.post(`${API}/booking`, {
    headers: await bearer(page),
    data: {
      teacherId: input.teacherId,
      byday: [0],
      startTimeLocal: input.time,
      tz: 'Asia/Riyadh',
      durationMin: 45,
      startsOn: sunday,
      kind: 'trial',
      package: 'trial',
      studentIds: family.studentIds,
      clientRequestId: randomUUID(),
      startsAt: riyadh(sunday, input.time).toISOString(),
    },
  });
  expect(res.status()).toBe(201);
  const { lessons } = (await res.json()) as { lessons: { id: string }[] };
  return { guardianId: family.guardianId, lessonId: lessons[0]?.id ?? '' };
}

test.describe('meeting link generated by the platform (settings.meeting_link_auto)', () => {
  test('auto: a plain confirmation while the lesson keeps the fixed link; static: the Meet template again', async ({ asRole, isMobile }) => {
    test.skip(isMobile, 'API-only scenario: the desktop run covers it');
    const teacherId = await resetAbrar();
    const prev = await setMeetLink(teacherId);
    try {
      await setAvailability(teacherId, [[0, '16:00', '19:00']]);
      const page = await asRole('admin');
      await page.goto('/admin/schedule');

      await setSetting('meeting_link_auto', true);
      const auto = await bookTrial(page, { teacherId, time: '16:00', name: 'لمى' });
      expect(await queuedFor(auto.guardianId)).toEqual([{ template_key: 'booking_confirmation_plain', lesson_id: auto.lessonId, status: 'queued' }]);
      const [row] = await withSql((sql) => sql<{ link: string | null }[]>`select meeting_link as link from public.lessons where id = ${auto.lessonId}`);
      expect(row?.link).toBe(MEET);

      await setSetting('meeting_link_auto', false);
      const fixed = await bookTrial(page, { teacherId, time: '18:00', name: 'رهف' });
      expect((await queuedFor(fixed.guardianId)).map((m) => m.template_key)).toEqual(['booking_confirmation_meet']);
    } finally {
      await restore(teacherId, prev);
    }
  });

  test('auto: the teacher dashboard offers the platform classroom only', async ({ asRole }) => {
    const teacherId = await resetAbrar();
    const prev = await setMeetLink(teacherId);
    try {
      const family = await seedFamily('أم جود', ['جود']);
      await seedLesson({ teacherId, studentId: family.studentIds[0] ?? '', startsAt: new Date(Date.now() + 2 * 86_400_000), minutes: 45 });
      const card = (page: Page) => page.getByRole('article', { name: /جود/ });

      // Static (the default): the fixed link at the top and on the card.
      const before = await asRole('teacher');
      await before.goto('/teacher');
      await before.getByRole('tab', { name: ar.teacherDash.week }).click();
      await expect(before.getByRole('region', { name: ar.teacherDash.joinLink }).getByRole('link', { name: ar.teacherDash.join })).toHaveAttribute('href', MEET);
      await expect(card(before).getByRole('link', { name: ar.classroom.joinMeeting })).toBeVisible();

      // Auto, in a fresh browser (GET /settings/public may be kept a minute): only the classroom.
      await setSetting('meeting_link_auto', true);
      const after = await asRole('teacher');
      await after.goto('/teacher');
      await after.getByRole('tab', { name: ar.teacherDash.week }).click();
      await expect(card(after).getByText(ar.classroom.enter).first()).toBeVisible();
      await expect(after.getByRole('region', { name: ar.teacherDash.joinLink })).toHaveCount(0);
      await expect(card(after).getByRole('link', { name: ar.classroom.joinMeeting })).toHaveCount(0);
    } finally {
      await restore(teacherId, prev);
    }
  });
});
